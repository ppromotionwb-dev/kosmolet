// Космолёт — страница ошибки загрузки. Владелец: core. Без kosmo API.
// Адрес: kosmo://error/?code=-105&desc=ERR_NAME_NOT_RESOLVED&url=https%3A%2F%2F...
'use strict';
(function () {
  const U = window.KUI;
  const $ = (id) => document.getElementById(id);
  const q = new URLSearchParams(location.search);
  const code = parseInt(q.get('code') || '0', 10) || 0;
  const desc = (q.get('desc') || q.get('error') || '').trim();
  // повторять можно только обычные адреса (не javascript:/data: и т.п.)
  const rawUrl = q.get('url') || '';
  const url = /^(https?|file|ftp):/i.test(rawUrl) ? rawUrl : '';
  const p = U.parseUrl(rawUrl);
  const host = p.hostU || '';
  const local = p.local;
  const port = (() => { try { return new URL(rawUrl).port; } catch (e) { return ''; } })();

  const NET = ['Проверьте подключение к интернету', 'Отключите VPN или прокси, если они включены'];
  // код → [заголовок, описание, подсказки, иконка, тон]
  const E = {
    '-2': ['Что-то пошло не так', 'Загрузка прервалась.', null],
    '-6': ['Файл не найден', 'Такого файла нет или он был перемещён.', null, 'file'],
    '-7': ['Слишком долгий ответ', 'Сервер не ответил вовремя.', NET, 'clock'],
    '-10': ['Нет доступа', 'Доступ к этому ресурсу запрещён.', null, 'lock'],
    '-20': ['Заблокировано', 'Страницу остановил блокировщик или расширение.', ['Добавьте сайт в исключения блокировщика в настройках'], 'shield', 'accent'],
    '-21': ['Сеть изменилась', 'Подключение сменилось во время загрузки.', ['Просто повторите'], 'wifi-off'],
    '-27': ['Заблокировано сайтом', 'Сайт запретил показывать эту страницу.', null, 'shield'],
    '-100': ['Соединение закрыто', 'Сервер неожиданно закрыл соединение.', NET, 'wifi-off'],
    '-101': ['Соединение сброшено', 'Соединение с сервером прервалось.', NET, 'wifi-off'],
    '-102': ['Сервер отклонил подключение', local ? 'На этом порту ничего не запущено.' : 'Сервер не принимает подключения.', local
      ? ['Проверьте, что локальный сервер запущен' + (port ? ' на порту ' + port : ''), 'Возможно, он слушает другой порт или адрес']
      : ['Проверьте адрес и порт', 'Сервер может быть временно выключен'], 'server', 'warn'],
    '-104': ['Не удалось подключиться', 'Подключение к серверу не установлено.', NET, 'wifi-off'],
    '-105': ['Сайт не найден', 'Не удалось найти адрес сервера' + (host ? ' ' + host : '') + '.', ['Проверьте адрес на опечатки', ...NET], 'search'],
    '-106': ['Нет интернета', 'Компьютер не подключён к сети.', ['Проверьте Wi-Fi или кабель', 'Перезапустите роутер'], 'wifi-off', 'warn'],
    '-107': ['Ошибка защищённого соединения', 'Сайт прислал неверный ответ при установке HTTPS.', null, 'lock', 'danger'],
    '-109': ['Адрес недоступен', 'До сервера не удалось достучаться.', NET, 'wifi-off'],
    '-118': ['Время ожидания истекло', 'Сервер слишком долго не отвечает.', NET, 'clock'],
    '-130': ['Прокси не отвечает', 'Не удалось подключиться через прокси-сервер.', ['Проверьте настройки прокси'], 'server'],
    '-137': ['Не удалось найти сервер', 'DNS не ответил.', NET, 'search'],
    '-200': ['Сертификат не подходит', 'Сертификат выдан для другого сайта — возможно, подмена.', null, 'lock', 'danger'],
    '-201': ['Сертификат просрочен', 'Срок действия сертификата истёк или часы компьютера идут неверно.', ['Проверьте дату и время на компьютере'], 'lock', 'danger'],
    '-202': ['Сертификат не заслуживает доверия', 'Сертификат выдан неизвестным центром.', local ? ['Для локальной разработки используйте http или доверенный сертификат'] : null, 'lock', 'danger'],
    '-300': ['Неверный адрес', 'Адрес записан с ошибкой.', ['Проверьте адрес'], 'link'],
    '-301': ['Адрес запрещён', 'Такие ссылки открывать нельзя.', null, 'shield'],
    '-302': ['Неизвестный протокол', 'Браузер не умеет открывать такие ссылки.', null, 'link'],
    '-312': ['Порт запрещён', 'Браузеры не открывают этот порт: он зарезервирован для других служб.', ['Запустите сервер на другом порту, например 3000 или 8080'], 'shield', 'warn'],
    '-310': ['Слишком много перенаправлений', 'Сайт перенаправляет по кругу.', ['Очистите cookies этого сайта', 'Проверьте правила редиректов на сервере'], 'rotate-cw', 'warn'],
    '-324': ['Пустой ответ', 'Сервер ничего не прислал.', local ? ['Посмотрите логи локального сервера'] : NET, 'server'],
    '-501': ['Небезопасный ответ', 'Сервер прислал небезопасный ответ.', null, 'lock', 'danger'],
  };
  let e = E[String(code)];
  if (!e) {
    if (code <= -200 && code > -300) e = ['Проблема с сертификатом', 'Защищённое соединение не установлено.', null, 'lock', 'danger'];
    else if (code <= -100 && code > -200) e = ['Не удалось подключиться', 'Соединение с сервером не установлено.', NET, 'wifi-off'];
    else e = ['Страница недоступна', 'Не удалось загрузить страницу.', null];
  }
  const [title, text, tips, icon, tone] = e;

  document.title = host || title; // во вкладке — домен, как в Chrome
  $('er-icon').innerHTML = window.KIcons.get(icon || 'alert-triangle', 24, { stroke: 1.6 });
  if (tone) $('er-icon').dataset.tone = tone;
  $('er-title').textContent = title;
  $('er-text').textContent = text;
  $('er-url').textContent = rawUrl ? U.readableUrl(rawUrl) : '';
  const tipsEl = $('er-tips');
  for (const t of tips || []) tipsEl.appendChild(U.h('li', t));
  $('er-code').textContent = (desc || 'ERR') + (code ? ' (' + code + ')' : '');

  const retry = $('er-retry');
  if (!url) retry.hidden = true;
  retry.addEventListener('click', () => { if (url) location.replace(url); });
  const copy = $('er-copy');
  if (!rawUrl) copy.hidden = true;
  copy.addEventListener('click', () => U.copyText(rawUrl, { message: 'Адрес скопирован' }));
  document.addEventListener('keydown', (ev) => {
    if (ev.key === 'Enter' && url && document.activeElement === document.body) location.replace(url);
  });
  retry.focus({ preventScroll: true });
})();
